package basics;

public class Tokens {
    public static void main(String args[])
    {
        int a ; //Keyword=int ; Identifier=a;
        System.out.println("keyword = "+" int"+" "+" , " +"Identifier = a");
        float b =1.5F;
        System.out.println("Literal is F " + b);
        double c = 1.77777777d;
        System.out.println("Literal is d " + c);
        System.out.println("Separator is : { }");

    }
}
