package basics;

public class TypeCasting {
    public static void main(String args[])
    {
        int a=10;
        float b = a;
        System.out.println("Implicit TypeCasting is = "+b);
        float c =20.7777f;
        int d = (int)c;
        System.out.println("Explicit TypeCasting is = "+d);
    }
}
