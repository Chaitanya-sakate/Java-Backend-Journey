package basics;

public class ForLoop {
    public static void main(String args[])
    {
        System.out.println("Reverse Natural no");
        for(int i=10;i>=1;i--)
        {
            System.out.println(i);
        }
        System.out.println("Natural no");
        for(int n=1;n<=10;n++)
        {
            System.out.println(n);
        }
    }
}
